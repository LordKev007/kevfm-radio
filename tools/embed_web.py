r"""Compress the KevFM web pages (web/*.html) into the firmware.

    python tools\embed_web.py

Writes yoRadio/src/plugins/KevFM/kevfm_pages.h: each page gzipped (deterministic, so the
file only changes when a page changes) as a PROGMEM byte array. The radio serves them
straight from flash, so pages always match the firmware and nothing is written to the
radio's small file storage. build.cmd and tools/build.sh run this first; the generated
header is committed so an Arduino IDE build works without it.
"""
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "yoRadio" / "src" / "plugins" / "KevFM" / "kevfm_pages.h"
PAGES = ["kevfm.html", "setup.html", "firmware.html", "settings.html"]


def main():
    lines = [
        "/* GENERATED by tools/embed_web.py from web/*.html - edit those, then rebuild. */",
        "#ifndef KEVFM_PAGES_H",
        "#define KEVFM_PAGES_H",
        "#include <Arduino.h>",
        "",
    ]
    total = 0
    for name in PAGES:
        raw = (WEB / name).read_bytes()
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        total += len(data)
        ident = "kevfm_page_" + name.replace(".", "_")
        lines.append(f"/* {name}: {len(raw)} bytes, gzipped {len(data)} */")
        lines.append(f"static const uint8_t {ident}[] PROGMEM = {{")
        for i in range(0, len(data), 20):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
        lines.append("};")
        lines.append(f"static const size_t {ident}_len = {len(data)};")
        lines.append("")
    lines.append("#endif")
    text = "\n".join(lines) + "\n"
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"embedded {len(PAGES)} pages, {total:,} bytes gzipped -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
